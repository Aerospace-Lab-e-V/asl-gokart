// Generates src/gen/signals.ts from schema/signals.yaml (the signal catalog).
// The catalog is compiled in so signal names in the preset views are type-checked.
//   bun scripts/gen-catalog.ts
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { parse } from "yaml";

const root = resolve(import.meta.dirname, "..");
const source = resolve(root, "../../schema/signals.yaml");
const target = resolve(root, "src/gen/signals.ts");

interface CatalogSignal {
    id: number;
    name: string;
    ecu: string;
    unit: string;
    rate_hz: number;
    min: number;
    max: number;
    description?: string;
    deprecated?: boolean;
}

const catalog = parse(readFileSync(source, "utf8")) as { signals: CatalogSignal[] };

const signals = catalog.signals
    .filter((s) => !s.deprecated)
    .map((s) => ({
        id: s.id,
        name: s.name,
        ecu: s.ecu,
        unit: s.unit,
        rateHz: s.rate_hz,
        min: s.min,
        max: s.max,
        description: s.description ?? "",
    }));

const out = `// Generated by scripts/gen-catalog.ts from schema/signals.yaml. Do not edit.

export interface SignalDef {
    id: number;
    name: string;
    ecu: string;
    unit: string;
    rateHz: number;
    min: number;
    max: number;
    description: string;
}

export const SIGNALS = ${JSON.stringify(signals, null, 4)} as const satisfies readonly SignalDef[];

export type SignalName = (typeof SIGNALS)[number]["name"];
`;

mkdirSync(dirname(target), { recursive: true });
writeFileSync(target, out);
console.log(`gen-catalog: ${signals.length} signals → ${target}`);
